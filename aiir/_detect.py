# Git trailer keys that indicate AI involvement.
# NOTE: "tool" is intentionally excluded — the trailer key "tool:" is a
# common conventional-commit scope prefix (e.g. "tool: update hammer") and
# produces false positives. The AI-specific "copilot:" trailer is retained.
AI_TRAILERS = [
    "assisted-by",
    "generated-by",
    "ai-assisted",
    "ai-model",
    "copilot",
]

