class TestBuildReleaseBundleLedger(unittest.TestCase):
    def test_ledger_passed_bundle_structure(self):
        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            ledger = _write_ledger(
                base, [_make_receipt("aaa"), _make_receipt("bbb", ai=True)]
            )
            bundle = build_release_bundle(
                receipts_path=ledger,
                policy_preset="balanced",
                release_name="v1.0.0",
                subject_name="git+https://example.com/repo@deadbeef",
                created_at="2026-06-06T00:00:00Z",
            )
            files = bundle["files"]
            self.assertEqual(bundle["verification_result"], "PASSED")
            self.assertEqual(bundle["result_code"], 0)
            # Required artifacts present.
            for name in (
                "manifest.json",
                "manifest.sha256",
                "verify-release.json",
                "vsa.intoto.json",
                "policy.json",
                "evidence-stream.json",
                "evidence-summary.json",
                "auditor-report.html",
                "verifier-instructions.md",
                "README.md",
            ):
                self.assertIn(name, files, name)
            # Two receipts re-serialized under receipts/.
            receipt_files = [k for k in files if k.startswith("receipts/")]
            self.assertEqual(len(receipt_files), 2)

    def test_manifest_anchor_fields(self):
        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            ledger = _write_ledger(base, [_make_receipt("aaa")])
            bundle = build_release_bundle(
                receipts_path=ledger,
                policy_preset="balanced",
                created_at="2026-06-06T00:00:00Z",
            )
            manifest = bundle["manifest"]
            self.assertEqual(manifest["schema"], BUNDLE_SCHEMA)
            self.assertEqual(manifest["bundle_format_version"], BUNDLE_FORMAT_VERSION)
            self.assertEqual(manifest["created_at"], "2026-06-06T00:00:00Z")
            self.assertEqual(manifest["aiir_version"], CLI_VERSION)
            self.assertTrue(manifest["boundary"]["declared_ai_provenance_only"])
            self.assertFalse(manifest["boundary"]["hidden_ai_detection"])
            # Every artifact has a sha256 that matches the file bytes.
            for entry in manifest["artifacts"]:
                content = bundle["files"][entry["path"]]
                self.assertEqual(entry["sha256"], hashlib.sha256(content).hexdigest())

