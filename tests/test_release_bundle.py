class TestCollectReceiptArtifacts(unittest.TestCase):
    def test_dir_skips_symlinked_receipt(self):
        if not hasattr(os, "symlink"):  # pragma: no cover - platform guard
            self.skipTest("symlinks unsupported")
        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            rdir = base / "rdir"
            rdir.mkdir()
            real = rdir / "real.json"
            real.write_text(json.dumps(_make_receipt("aaa")), encoding="utf-8")
            link = rdir / "link.json"
            try:
                os.symlink(real, link)
            except OSError:  # pragma: no cover - platform guard
                self.skipTest("symlink creation failed")
            artifacts = collect_receipt_artifacts(str(rdir), [])
            names = [a[0] for a in artifacts]
            self.assertIn("receipts/real.json", names)
            self.assertNotIn("receipts/link.json", names)

    def test_dir_skips_symlinked_sidecars(self):
        if not hasattr(os, "symlink"):  # pragma: no cover - platform guard
            self.skipTest("symlinks unsupported")
        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            rdir = base / "rdir"
            rdir.mkdir()
            real = rdir / "r.json"
            real.write_text(json.dumps(_make_receipt("aaa")), encoding="utf-8")
            # Symlinked sidecars must be skipped.
            target = base / "outside.sig"
            target.write_text("{}", encoding="utf-8")
            try:
                os.symlink(target, Path(str(real) + ".sigstore"))
                os.symlink(target, real.with_suffix(".cbor"))
            except OSError:  # pragma: no cover - platform guard
                self.skipTest("symlink creation failed")
            artifacts = collect_receipt_artifacts(str(rdir), [])
            self.assertFalse(any(a[0].startswith("signatures/") for a in artifacts))
            self.assertFalse(any(a[0].endswith(".cbor") for a in artifacts))

    def test_jsonl_uses_receipt_id_when_no_sha(self):
        receipt = _make_receipt("aaa")
        del receipt["commit"]["sha"]
        receipt["receipt_id"] = "weird/id*name"
        artifacts = collect_receipt_artifacts("not-a-dir.jsonl", [receipt])
        self.assertEqual(len(artifacts), 1)
        relpath = artifacts[0][0]
        # Unsafe characters stripped from the on-disk name.
        self.assertNotIn("/", relpath.split("receipts/")[1])
        self.assertNotIn("*", relpath)

    def test_jsonl_non_dict_commit(self):
        receipt = _make_receipt("aaa")
        receipt["commit"] = "not-a-dict"
        receipt["receipt_id"] = ""
        artifacts = collect_receipt_artifacts("ledger.jsonl", [receipt])
        self.assertTrue(artifacts[0][0].endswith("receipt.json"))


