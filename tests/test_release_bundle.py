class TestRoundTripIntegrity(unittest.TestCase):
    def test_written_bundle_artifacts_match_manifest(self):
        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            ledger = _write_ledger(base, [_make_receipt("aaa"), _make_receipt("bbb")])
            bundle = build_release_bundle(
                receipts_path=ledger, policy_preset="balanced"
            )
            out = base / "evidence"
            write_release_bundle(bundle, str(out))
            manifest = json.loads((out / "manifest.json").read_text())
            for entry in manifest["artifacts"]:
                data = (out / entry["path"]).read_bytes()
                self.assertEqual(
                    hashlib.sha256(data).hexdigest(), entry["sha256"], entry["path"]
                )
            # manifest.sha256 matches manifest.json bytes.
            sha_line = (out / "manifest.sha256").read_text().split()[0]
            self.assertEqual(
                sha_line,
                hashlib.sha256((out / "manifest.json").read_bytes()).hexdigest(),
            )


