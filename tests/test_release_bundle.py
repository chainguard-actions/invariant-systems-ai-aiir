class TestWriteReleaseBundle(unittest.TestCase):
    def _simple_bundle(self) -> dict:
        files: "OrderedDict[str, bytes]" = OrderedDict()
        files["manifest.json"] = b"{}"
        files["receipts/a.json"] = b"{}"
        return {"files": files, "manifest": {"artifacts": []}}

    def test_writes_files(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / "bundle"
            path = write_release_bundle(self._simple_bundle(), str(out))
            self.assertTrue((Path(path) / "manifest.json").is_file())
            self.assertTrue((Path(path) / "receipts" / "a.json").is_file())

    def test_str_content_is_encoded(self):
        files: "OrderedDict[str, object]" = OrderedDict()
        files["note.txt"] = "hello"  # str, not bytes
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / "bundle"
            write_release_bundle({"files": files}, str(out))
            self.assertEqual((out / "note.txt").read_text(), "hello")

    def test_empty_files_raises(self):
        with tempfile.TemporaryDirectory() as tmp:
            with self.assertRaises(ValueError):
                write_release_bundle({"files": {}}, str(Path(tmp) / "x"))

    def test_non_empty_dir_without_overwrite_raises(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / "bundle"
            out.mkdir()
            (out / "existing.txt").write_text("x")
            with self.assertRaises(ValueError):
                write_release_bundle(self._simple_bundle(), str(out))

    def test_overwrite_allows_non_empty_dir(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / "bundle"
            out.mkdir()
            (out / "existing.txt").write_text("x")
            path = write_release_bundle(self._simple_bundle(), str(out), overwrite=True)
            self.assertTrue((Path(path) / "manifest.json").is_file())

    def test_output_is_symlink_raises(self):
        if not hasattr(os, "symlink"):  # pragma: no cover - platform guard
            self.skipTest("symlinks unsupported")
        with tempfile.TemporaryDirectory() as tmp:
            real = Path(tmp) / "real"
            real.mkdir()
            link = Path(tmp) / "link"
            try:
                os.symlink(real, link)
            except OSError:  # pragma: no cover - platform guard
                self.skipTest("symlink creation failed")
            with self.assertRaises(ValueError):
                write_release_bundle(self._simple_bundle(), str(link))

    def test_output_exists_as_file_raises(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / "afile"
            out.write_text("x")
            with self.assertRaises(ValueError):
                write_release_bundle(self._simple_bundle(), str(out))

    def test_refuses_write_through_symlinked_parent(self):
        if not hasattr(os, "symlink"):  # pragma: no cover - platform guard
            self.skipTest("symlinks unsupported")
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / "bundle"
            out.mkdir()
            outside = Path(tmp) / "outside"
            outside.mkdir()
            try:
                os.symlink(outside, out / "receipts")
            except OSError:  # pragma: no cover - platform guard
                self.skipTest("symlink creation failed")
            files: "OrderedDict[str, bytes]" = OrderedDict()
            files["receipts/a.json"] = b"{}"
            with self.assertRaises(ValueError):
                write_release_bundle({"files": files}, str(out), overwrite=True)


