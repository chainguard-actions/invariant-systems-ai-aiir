class TestBuildReleaseBundleDir(unittest.TestCase):
    def test_dir_copies_receipts_and_sidecars(self):
        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            rdir = Path(_write_receipt_dir(base, [_make_receipt("aaa", signed=True)]))
            # Add a sigstore sidecar and a cbor sidecar for the receipt.
            receipt_json = sorted(rdir.glob("*.json"))[0]
            Path(str(receipt_json) + ".sigstore").write_text("{}", encoding="utf-8")
            receipt_json.with_suffix(".cbor").write_bytes(b"\xa0")
            bundle = build_release_bundle(
                receipts_path=str(rdir), policy_preset="balanced"
            )
            files = bundle["files"]
            self.assertTrue(any(k.startswith("signatures/") for k in files))
            self.assertTrue(any(k.endswith(".cbor") for k in files))
            # Original receipt bytes copied verbatim.
            self.assertEqual(
                files[f"receipts/{receipt_json.name}"], receipt_json.read_bytes()
            )

    def test_policy_path_explicit_file(self):
        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            ledger = _write_ledger(base, [_make_receipt("aaa")])
            policy_file = base / "custom-policy.json"
            policy_file.write_text(
                json.dumps({"enforcement": "warn", "require_signing": False}),
                encoding="utf-8",
            )
            bundle = build_release_bundle(
                receipts_path=ledger, policy_path=str(policy_file)
            )
            policy = json.loads(bundle["files"]["policy.json"])
            self.assertEqual(policy["enforcement"], "warn")

    def test_policy_path_missing_raises(self):
        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            ledger = _write_ledger(base, [_make_receipt("aaa")])
            # verify_release() validates the policy path first and raises.
            with self.assertRaises(FileNotFoundError):
                build_release_bundle(
                    receipts_path=ledger, policy_path=str(base / "missing.json")
                )

    def test_default_policy_when_none(self):
        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            ledger = _write_ledger(base, [_make_receipt("aaa")])
            cwd = os.getcwd()
            try:
                os.chdir(tmp)
                bundle = build_release_bundle(receipts_path=ledger)
            finally:
                os.chdir(cwd)
            self.assertIn("policy.json", bundle["files"])


